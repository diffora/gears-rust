#[cfg(test)]
mod tests {
    use super::test_support::sample_model;
    use super::*;
    use toolkit_gts::gts_id;

    #[test]
    fn model_round_trips_through_json_with_design_wire_names() {
        let model = sample_model();
        let json = serde_json::to_value(&model).expect("serializes");

        assert_eq!(json["name"], "gpt-4o");
        assert_eq!(json["canonical_id"], "openai::gpt-4o");
        assert_eq!(json["version"], 1);
        assert_eq!(json["sharing_mode"], "tenant");
        assert_eq!(json["approval"]["state"], "approved");
        assert_eq!(json["info"]["model_version"], serde_json::Value::Null);
        assert!(json["info"].get("version").is_none());
        assert_eq!(json["info"]["cost"], serde_json::json!({}));
        assert_eq!(json["info"]["base_url"], "https://api.openai.com/v1");
        assert_eq!(json["info"]["secret_ref"], "platform-openai-key");
        assert_eq!(
            json["info"]["gts_type"],
            gts_id!("cf.genai.model.provider.v1~cf.genai._.openai.v1~")
        );
        assert_eq!(
            json["info"]["provider_settings"]["oagw_alias"],
            "openai-prod"
        );
        assert_eq!(
            json["info"]["supported_api"],
            serde_json::json!(["completion"])
        );

        let back: ModelV1 = serde_json::from_value(json).expect("deserializes");
        assert_eq!(back, model);
    }

    #[test]
    fn model_entry_flattens_nothing() {
        let entry = ModelEntryV1 {
            model: sample_model(),
            inherited: true,
            shadowed: false,
            provider_enabled: true,
            available_for_eval: true,
        };
        let json = serde_json::to_value(&entry).expect("serializes");
        assert_eq!(json["inherited"], true);
        assert_eq!(json["model"]["canonical_id"], "openai::gpt-4o");
    }
}
