/// A provider as returned by the management operations (DESIGN §3.3
/// Management responses).
///
/// The flags describe catalog state for the caller's tenant only; the PDP
/// `evaluate` decision is not included.
#[allow(clippy::struct_excessive_bools)]
#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize, schemars::JsonSchema)]
#[non_exhaustive]
pub struct ProviderEntryV1 {
    pub provider: ProviderV1,
    /// Owned by an ancestor of the caller's tenant; read-only.
    pub inherited: bool,
    /// Inherited and not the winner of its slug for the caller.
    pub shadowed: bool,
    /// Winner of its slug for the caller and enabled.
    pub available_for_eval: bool,
}

impl ProviderEntryV1 {
    /// An entry for `provider` with every flag false.
    #[must_use]
    pub fn new(provider: ProviderV1) -> Self {
        Self {
            provider,
            inherited: false,
            shadowed: false,
            available_for_eval: false,
        }
    }
}

/// A model as returned by the management operations (DESIGN §3.3
/// Management responses).
///
/// The flags describe catalog state for the caller's tenant only; the PDP
/// `evaluate` decision is not included.
#[allow(clippy::struct_excessive_bools)]
#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize, schemars::JsonSchema)]
#[non_exhaustive]
pub struct ModelEntryV1 {
    pub model: ModelV1,
    /// Owned by an ancestor of the caller's tenant; read-only.
    pub inherited: bool,
    /// Its provider is not the winner of its slug for the caller.
    pub shadowed: bool,
    pub provider_enabled: bool,
    /// Not shadowed, provider enabled, and approved.
    pub available_for_eval: bool,
}

impl ModelEntryV1 {
    /// An entry for `model` with every flag false.
    #[must_use]
    pub fn new(model: ModelV1) -> Self {
        Self {
            model,
            inherited: false,
            shadowed: false,
            provider_enabled: false,
            available_for_eval: false,
        }
    }
}

