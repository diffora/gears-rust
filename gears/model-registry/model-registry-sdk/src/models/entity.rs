/// A tenant-owned catalog entry for one model of one provider (DESIGN §3.1
/// Model).
#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize, schemars::JsonSchema)]
#[non_exhaustive]
pub struct ModelV1 {
    /// Model id, generated by the gear.
    pub id: Uuid,
    /// Owning tenant. Always equal to the provider's `tenant_id`. Immutable.
    pub tenant_id: Uuid,
    /// The provider that serves the model. Immutable.
    pub provider_id: Uuid,
    /// 1–128 characters: lowercase letters, digits, hyphen, dot, underscore.
    /// Chosen by the caller on create. Unique among the models of the
    /// provider. Immutable. Right part of `canonical_id`; independent of
    /// `info.provider_model_id`.
    pub name: String,
    /// `provider_slug::name`, built by the gear. Never changes.
    pub canonical_id: String,
    /// Descendants see the model only when it is `Shared` and its provider
    /// is `Shared`. Default [`SharingMode::Tenant`].
    #[serde(default)]
    pub sharing_mode: SharingMode,
    pub approval: ApprovalV1,
    pub info: ModelInfoV1,
    /// Row version: 1 on create, incremented by every update. The `ETag` on
    /// REST; updates and deletes are conditional on it through
    /// `expected_version`.
    pub version: i64,
    pub created_at: DateTime<Utc>,
    /// Subject that created the model.
    pub created_by: Uuid,
    pub updated_at: DateTime<Utc>,
    /// Subject that last changed the model.
    pub updated_by: Uuid,
}

impl ModelV1 {
    /// A model as first written by `created_by` at `created_at`: sharing
    /// mode [`SharingMode::Tenant`], approved by `created_by` at
    /// `created_at`, `version` 1, and the update audit equal to the creation
    /// audit.
    #[must_use]
    #[allow(clippy::too_many_arguments)]
    pub fn new(
        id: Uuid,
        tenant_id: Uuid,
        provider_id: Uuid,
        name: impl Into<String>,
        canonical_id: impl Into<String>,
        info: ModelInfoV1,
        created_by: Uuid,
        created_at: DateTime<Utc>,
    ) -> Self {
        Self {
            id,
            tenant_id,
            provider_id,
            name: name.into(),
            canonical_id: canonical_id.into(),
            sharing_mode: SharingMode::Tenant,
            approval: ApprovalV1::new(ApprovalState::Approved, created_by, created_at),
            info,
            version: 1,
            created_at,
            created_by,
            updated_at: created_at,
            updated_by: created_by,
        }
    }
}

