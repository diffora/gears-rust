use chrono::{DateTime, Utc};
use uuid::Uuid;

use crate::models::{ApprovalState, ModelInfoV1, SharingMode};

// ---------------------------------------------------------------------------
// ProviderV1
// ---------------------------------------------------------------------------

/// A tenant-owned provider record (DESIGN §3.1 Provider).
#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize, schemars::JsonSchema)]
pub struct ProviderV1 {
    /// Provider id, generated by the gear.
    pub id: Uuid,
    /// Owning tenant. Immutable.
    pub tenant_id: Uuid,
    /// 1–64 characters: lowercase letters, digits, hyphen. Unique among the
    /// providers of the owning tenant. Immutable. Shadowing key and left
    /// part of every canonical id.
    pub slug: String,
    /// Display name, 1–255 characters.
    pub name: String,
    /// Provider GTS type, derived from
    /// [`PROVIDER_BASE_TYPE`](crate::gts::PROVIDER_BASE_TYPE). Names the LLM
    /// Gateway plugin family that evaluates the provider's models. Changes
    /// only through type migration, together with the `gts_type` of every
    /// model of the provider.
    pub gts_type: gts::GtsTypeId,
    /// When false, no model of this provider can be evaluated by the owner
    /// or any inheriting tenant. Default true.
    pub enabled: bool,
    /// Default [`SharingMode::Tenant`].
    pub sharing_mode: SharingMode,
    /// Whether the platform can manage the provider runtime itself.
    /// Informational. Default false.
    pub managed: bool,
    /// Opaque provider metadata, stored and returned unchanged.
    pub metadata: Option<serde_json::Value>,
    /// Row version: 1 on create, incremented by every update. The `ETag` on
    /// REST; updates and deletes are conditional on it through
    /// `expected_version`.
    pub version: i64,
    pub created_at: DateTime<Utc>,
    /// Subject that created the provider.
    pub created_by: Uuid,
    pub updated_at: DateTime<Utc>,
    /// Subject that last changed the provider.
    pub updated_by: Uuid,
}

// ---------------------------------------------------------------------------
// ApprovalV1
// ---------------------------------------------------------------------------

/// The owning tenant's latest approval decision on a model (DESIGN §3.1
/// Approval).
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize, schemars::JsonSchema,
)]
pub struct ApprovalV1 {
    pub state: ApprovalState,
    /// Subject that made the latest decision.
    pub decided_by: Uuid,
    /// Time of the latest decision.
    pub decided_at: DateTime<Utc>,
}

// ---------------------------------------------------------------------------
// ModelV1
// ---------------------------------------------------------------------------

/// A tenant-owned catalog entry for one model of one provider (DESIGN §3.1
/// Model).
#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize, schemars::JsonSchema)]
pub struct ModelV1 {
    /// Model id, generated by the gear.
    pub id: Uuid,
    /// Owning tenant. Always equal to the provider's `tenant_id`. Immutable.
    pub tenant_id: Uuid,
    /// The provider that serves the model. Immutable.
    pub provider_id: Uuid,
    /// 1–128 characters: lowercase letters, digits, hyphen, dot, underscore.
    /// Chosen by the caller on create. Unique among the models of the
    /// provider. Immutable. Right part of `canonical_id`; independent of
    /// `info.provider_model_id`.
    pub name: String,
    /// `provider_slug::name`, built by the gear. Never changes.
    pub canonical_id: String,
    /// Descendants see the model only when it is `Shared` and its provider
    /// is `Shared`. Default [`SharingMode::Tenant`].
    pub sharing_mode: SharingMode,
    pub approval: ApprovalV1,
    pub info: ModelInfoV1,
    /// Row version: 1 on create, incremented by every update. The `ETag` on
    /// REST; updates and deletes are conditional on it through
    /// `expected_version`.
    pub version: i64,
    pub created_at: DateTime<Utc>,
    /// Subject that created the model.
    pub created_by: Uuid,
    pub updated_at: DateTime<Utc>,
    /// Subject that last changed the model.
    pub updated_by: Uuid,
}

// ---------------------------------------------------------------------------
// Management entries
// ---------------------------------------------------------------------------

/// A provider as returned by the management operations (DESIGN §3.3
/// Management responses).
///
/// The flags describe catalog state for the caller's tenant only; the PDP
/// `evaluate` decision is not included.
#[allow(clippy::struct_excessive_bools)]
#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize, schemars::JsonSchema)]
pub struct ProviderEntryV1 {
    pub provider: ProviderV1,
    /// Owned by an ancestor of the caller's tenant; read-only.
    pub inherited: bool,
    /// Inherited and not the winner of its slug for the caller.
    pub shadowed: bool,
    /// Winner of its slug for the caller and enabled.
    pub available_for_eval: bool,
}

/// A model as returned by the management operations (DESIGN §3.3
/// Management responses).
///
/// The flags describe catalog state for the caller's tenant only; the PDP
/// `evaluate` decision is not included.
#[allow(clippy::struct_excessive_bools)]
#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize, schemars::JsonSchema)]
pub struct ModelEntryV1 {
    pub model: ModelV1,
    /// Owned by an ancestor of the caller's tenant; read-only.
    pub inherited: bool,
    /// Its provider is not the winner of its slug for the caller.
    pub shadowed: bool,
    pub provider_enabled: bool,
    /// Not shadowed, provider enabled, and approved.
    pub available_for_eval: bool,
}

